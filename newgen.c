void PCIHelperf()
{

    EFI_GUID PciIoGuid = EFI_PCI_IO_PROTOCOL_GUID;

    UINTN handleCount = 0;
    EFI_HANDLE *handles = NULL;

    EFI_STATUS st = uefi_call_wrapper(gBS->LocateHandleBuffer,5,ByProtocol,&PciIoGuid,NULL,&handleCount,&handles);
    for (UINTN i = 0; i < handleCount; i++)
    {
        EFI_PCI_IO_PROTOCOL *PciIo = NULL;
        st = uefi_call_wrapper(gBS->HandleProtocol,3,handles[i],&PciIoGuid,(VOID**)&PciIo);
        if (EFI_ERROR(st) || !PciIo) continue;
        seg=0, bus=0, dev=0, fun=0;

        st = uefi_call_wrapper(PciIo->GetLocation,5,PciIo,&seg,&bus,&dev,&fun);
        if (EFI_ERROR(st)) continue;

        ProbeOne(PciIo, seg, bus, dev, fun);
        PciDevices[i].VendorId = vid;
        PciDevices[i].DeviceId = did;
        PciDevices[i].Class = base;
        PciDevices[i].SubClass = sub;
        PciDevices[i].ProgIF = progIf;
        PciDevices[i].Segment = seg;
        PciDevices[i].Bus = bus;
        PciDevices[i].Device = dev;
        PciDevices[i].Function = fun;
        PciDevices[i].Bar[0]=BaseAddress;
        PciDevices[i].Bar[1]=bar1;
        PciDevices[i].Bar[2]=bar2;
        PciDevices[i].Bar[3]=bar3;
        PciDevices[i].Bar[4]=bar4;
        PciDevices[i].Bar[5]=bar5;
        Print(L"raw Bar %llu and BaseAddress %llu\n", bar,BaseAddress);
    }

    if (handles) FreePool(handles);
    GetKey();
}
void ScFade(UINT32 start,UINT32 end)
{
    UINT8 r1 = (start >> 16) & 0xFF;
    UINT8 g1 = (start >> 8) & 0xFF;
    UINT8 b1 = start & 0xFF;

    UINT8 r2 = (end >> 16) & 0xFF;
    UINT8 g2 = (end >> 8) & 0xFF;
    UINT8 b2 = end & 0xFF;

    for(int i=0;i<=100;i+=4)
    {
        UINT8 r = r1 + ((r2-r1)*i)/100;
        UINT8 g = g1 + ((g2-g1)*i)/100;
        UINT8 b = b1 + ((b2-b1)*i)/100;

        UINT32 col = (r<<16)|(g<<8)|b;
        FillScreen(col);
    }
}
